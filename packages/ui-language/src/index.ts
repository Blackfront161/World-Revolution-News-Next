export function isUiLanguage(value: unknown): value is UiLanguage {
  return typeof value === 'string' && (uiLanguageIds as readonly string[]).includes(value);
}

/** Unknown, unreadable, or missing values intentionally fail closed to English. */
export function normalizeUiLanguage(value: unknown): UiLanguage {
  return isUiLanguage(value) ? value : defaultUiLanguage;
}

