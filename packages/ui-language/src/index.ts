export const registeredUiLanguages = uiLanguageIds;

export function isRegisteredUiLanguage(value: UiLanguage): boolean {
  return (registeredUiLanguages as readonly UiLanguage[]).includes(value);
}

export function getUiCopy(language: UiLanguage): UiCopy {
  return uiCopyByLanguage[language];
}

export function formatUiCopy(
  template: string,
  values: Readonly<Record<string, string | number>>,
): string {
  return template.replace(/\{([a-zA-Z][a-zA-Z0-9]*)\}/gu, (placeholder, name: string) => {
    const value = values[name];
    return value === undefined ? placeholder : String(value);
  });
}

export function uiLanguageOptionLabel(language: UiLanguage, copy: UiCopy): string {
  return formatUiCopy(copy.languageOptionName, {
    language: uiLanguageNativeNames[language],
    code: language.toUpperCase(),
  });
}

