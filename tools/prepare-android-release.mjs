import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { lstat, mkdir, mkdtemp, readFile, readdir, realpath, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const toolName = 'WRN Android release preparation';
const maximumFiles = 5_000;
const maximumFileBytes = 64 * 1024 * 1024;
const maximumTotalBytes = 256 * 1024 * 1024;
const sourcePaths = [
  'apps/mobile/src',
  'apps/mobile/public',
  'apps/mobile/index.html',
  'apps/mobile/vite.config.ts',
  'apps/mobile/android',
  'apps/mobile/capacitor.config.ts',
  'apps/mobile/package.json',
  'package.json',
  'packages',
  'pnpm-lock.yaml',
  'tools/browser-content-aliases.mjs',
  'tools/prepare-android-release.mjs',
];
const bridgePaths = [
  'apps/mobile/android/app/src/main/assets/capacitor.config.json',
  'apps/mobile/android/app/src/main/assets/capacitor.plugins.json',
  'apps/mobile/android/app/src/main/assets/public/cordova.js',
  'apps/mobile/android/app/src/main/assets/public/cordova_plugins.js',
];

function fail(message) {
  throw new Error(`${toolName}: ${message}`);
}

function sha256(bytes) {
  return createHash('sha256').update(bytes).digest('hex');
}

function git(root, args) {
  return execFileSync('git', args, {
    cwd: root,
    encoding: 'utf8',
    stdio: ['ignore', 'pipe', 'pipe'],
  });
}

function relativeSafe(root, candidate, label) {
  const resolved = path.resolve(candidate);
  const relative = path.relative(root, resolved);
  if (!relative || relative.startsWith('..') || path.isAbsolute(relative))
    fail(`${label} leaves the workspace`);
  return { resolved, relative };
}

async function inspectPath(root, candidate, label) {
  const { resolved, relative } = relativeSafe(root, candidate, label);
  const realRoot = await realpath(root);
  if ((await lstat(root)).isSymbolicLink()) fail('workspace root is a link or junction');
  let cursor = root;
  for (const segment of relative.split(path.sep)) {
    cursor = path.join(cursor, segment);
    const details = await lstat(cursor);
    if (details.isSymbolicLink()) fail(`${label} uses a link or junction`);
    const physical = await realpath(cursor);
    if (physical !== realRoot && !physical.startsWith(`${realRoot}${path.sep}`))
      fail(`${label} escapes the physical workspace`);
  }
  return resolved;
}

async function regularFile(root, candidate, label) {
  const resolved = await inspectPath(root, candidate, label);
  const details = await lstat(resolved);
  if (!details.isFile() || details.size > maximumFileBytes)
    fail(`${label} is not a bounded regular file`);
  return { resolved, bytes: await readFile(resolved) };
}

async function regularDependencyFile(root, candidate, label) {
  const resolved = path.resolve(candidate);
  const physical = await realpath(resolved);
  const realRoot = await realpath(root);
  if (physical !== realRoot && !physical.startsWith(`${realRoot}${path.sep}`))
    fail(`${label} escapes the physical workspace`);
  const details = await lstat(physical);
  if (!details.isFile() || details.size > maximumFileBytes)
    fail(`${label} is not a bounded regular file`);
  return { resolved: physical, bytes: await readFile(physical) };
}

async function listFiles(root, directory, label) {
  const resolved = await inspectPath(root, directory, label);
  const result = [];
  const visit = async (current) => {
    const entries = await readdir(current, { withFileTypes: true });
    for (const entry of entries) {
      if (entry.name === '.' || entry.name === '..') fail(`${label} has an unsafe path`);
      const next = path.join(current, entry.name);
      const relative = path.relative(directory, next).split(path.sep).join('/');
      if (entry.isDirectory()) await visit(next);
      else {
        if (!entry.isFile() || entry.isSymbolicLink()) fail(`${label} contains a non-regular file`);
        result.push({ absolute: await inspectPath(root, next, `${label}/${relative}`), relative });
        if (result.length > maximumFiles) fail(`${label} contains too many files`);
      }
    }
  };
  await visit(resolved);
  return result.sort((left, right) => left.relative.localeCompare(right.relative));
}

function groovyLiteral(value) {
  return value.replaceAll('\\', '\\\\').replaceAll("'", "\\'");
}

function initScript(expectedReceiptPath, expectedReceiptSha256) {
  return (
    `// Generated by tools/prepare-android-release.mjs. This does not sign or execute Gradle.\n` +
    `import java.nio.file.Files\n` +
    `import java.nio.file.LinkOption\n` +
    `import java.security.MessageDigest\n` +
    `import groovy.json.JsonSlurper\n` +
    `def wrnSha256 = { file ->\n` +
    `  def digest = MessageDigest.getInstance('SHA-256')\n` +
    `  file.withInputStream { input -> byte[] buffer = new byte[8192]; for (int read; (read = input.read(buffer)) != -1;) digest.update(buffer, 0, read) }\n` +
    `  return digest.digest().collect { String.format('%02x', it) }.join()\n` +
    `}\n` +
    `def wrnGit = { workspace, arguments ->\n` +
    `  def process = new ProcessBuilder((['git'] + arguments) as List).directory(workspace).redirectErrorStream(true).start()\n` +
    `  def output = process.inputStream.getText('UTF-8')\n` +
    `  if (process.waitFor() != 0) throw new GradleException('Required local Git verification failed')\n` +
    `  return output\n` +
    `}\n` +
    `def wrnExpectedReceipt = new File('${groovyLiteral(expectedReceiptPath)}').canonicalFile\n` +
    `def wrnExpectedReceiptSha256 = '${expectedReceiptSha256}'\n` +
    `def wrnVerifySnapshot = { selectedPath ->\n` +
    `  def receiptPath = System.getProperty('wrn.receipt')\n` +
    `  if (receiptPath == null) throw new GradleException('Explicit wrn.receipt is required')\n` +
    `  def receiptFile = new File(receiptPath).canonicalFile\n` +
    `  if (!receiptFile.isFile()) throw new GradleException('Bound release receipt is missing')\n` +
    `  if (receiptFile != wrnExpectedReceipt || wrnSha256(receiptFile) != wrnExpectedReceiptSha256) throw new GradleException('Bound release receipt does not match the prepared snapshot')\n` +
    `  def receipt = new JsonSlurper().parse(receiptFile)\n` +
    `  if (receipt.schema != 'wrn.android-release-preparation.v1' || receipt.dirty?.rejected || !(receipt.assets instanceof List)) throw new GradleException('Bound release receipt is invalid')\n` +
    `  def selected = new File(selectedPath).canonicalFile\n` +
    `  def expected = new File(receiptFile.parentFile, String.valueOf(receipt.assetsDirectory)).canonicalFile\n` +
    `  if (selected != expected || receiptFile.parentFile.canonicalFile != selected.parentFile.canonicalFile) throw new GradleException('wrn.assets is not the receipt-bound stage')\n` +
    `  def workspace = gradle.rootProject.projectDir.toPath().resolve('../../..').normalize().toFile().canonicalFile\n` +
    `  if (wrnGit(workspace, ['rev-parse', '--verify', 'HEAD^{commit}']).trim() != receipt.sourceCommit) throw new GradleException('Git HEAD differs from the bound receipt')\n` +
    `  if (wrnGit(workspace, ['status', '--porcelain=v1', '--untracked-files=all', '--'] + receipt.sourcePaths) != '') throw new GradleException('Bound release sources are dirty')\n` +
    `  def actual = [:]; def stream = Files.walk(selected.toPath()); try { stream.forEach { value -> if (value != selected.toPath()) { if (Files.isSymbolicLink(value)) throw new GradleException('Stage contains a link'); if (Files.isRegularFile(value, LinkOption.NOFOLLOW_LINKS)) { def relative = selected.toPath().relativize(value).toString().replace(File.separator, '/'); actual[relative] = [bytes: Files.size(value), sha256: wrnSha256(value.toFile())] } else if (!Files.isDirectory(value, LinkOption.NOFOLLOW_LINKS)) throw new GradleException('Stage contains a non-regular entry') } } } finally { stream.close() }\n` +
    `  def expectedAssets = [:]; receipt.assets.each { entry -> if (!(entry.path instanceof String) || !(entry.bytes instanceof Number) || !(entry.sha256 instanceof String) || expectedAssets.put(entry.path, [bytes: entry.bytes.longValue(), sha256: entry.sha256]) != null) throw new GradleException('Receipt asset manifest is invalid') }\n` +
    `  if (actual != expectedAssets) throw new GradleException('Stage assets differ from the receipt manifest')\n` +
    `}\n` +
    `gradle.beforeProject { project ->\n` +
    `  if (project.path == ':app') {\n` +
    `    project.plugins.withId('com.android.application') {\n` +
    `      def selected = System.getProperty('wrn.assets')\n` +
    `      if (selected == null || !new File(selected).isDirectory()) throw new GradleException('Explicit existing wrn.assets directory required')\n` +
    `      wrnVerifySnapshot(selected)\n` +
    `      project.android.sourceSets.main.assets.setSrcDirs([new File(selected)])\n` +
    `    }\n` +
    `  }\n` +
    `}\n` +
    `gradle.taskGraph.whenReady { graph ->\n` +
    `  if (gradle.startParameter.taskNames != [':app:bundleRelease']) throw new GradleException('Only :app:bundleRelease is permitted')\n` +
    `  if (gradle.rootProject.project(':app').android.buildTypes.release.signingConfig != null) throw new GradleException('Release signing configuration must remain unset')\n` +
    `  def releaseMetadataTasks = ['stripreleasedebugsymbols', 'mergereleasenativedebugmetadata', 'writereleasesigningconfigversions']\n` +
    `  def unsignedBundleSigningTask = ':app:signReleaseBundle'\n` +
    `  graph.allTasks.each { task ->\n` +
    `    def name = task.name.toLowerCase()\n` +
    `    def isExactUnsignedBundleSigningTask = task.path == unsignedBundleSigningTask && name == 'signreleasebundle'\n` +
    `    if (((name.contains('debug') || name.contains('sign')) && !releaseMetadataTasks.contains(name) && !isExactUnsignedBundleSigningTask) || name.contains('install') || name.contains('connected') || name.contains('androidtest')) throw new GradleException('Task outside unsigned release bundle scope: ' + task.path)\n` +
    `  }\n` +
    `}\n`
  );
}

async function writeFresh(stage, relative, bytes, records) {
  if (
    !/^[A-Za-z0-9._/-]+$/u.test(relative) ||
    relative.split('/').some((part) => !part || part === '.' || part === '..')
  )
    fail('generated output path is unsafe');
  const target = path.join(stage, ...relative.split('/'));
  await mkdir(path.dirname(target), { recursive: true });
  await writeFile(target, bytes, { flag: 'wx' });
  records.push({ path: relative, bytes: bytes.byteLength, sha256: sha256(bytes) });
}

function scopedDirty(root) {
  return git(root, ['status', '--porcelain=v1', '--untracked-files=all', '--', ...sourcePaths])
    .split(/\r?\n/u)
    .filter(Boolean);
}

/**
 * Creates a local staging snapshot only. The generated init script verifies its
 * receipt before a separately controlled Gradle invocation; this function never
 * invokes Gradle, writes into Android sources, signs, uploads, or changes a version.
 */
export async function prepareAndroidRelease({
  workspaceRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..'),
  now = () => new Date(),
  capacitorBridgePath,
} = {}) {
  const requestedRoot = path.resolve(workspaceRoot);
  if ((await lstat(requestedRoot)).isSymbolicLink()) fail('workspace root is a link or junction');
  const root = await realpath(requestedRoot);
  const work = path.join(root, 'work');
  await mkdir(work, { recursive: true });
  await inspectPath(root, work, 'work directory');
  const output = await mkdtemp(path.join(work, 'wrn-android-release-'));
  const stage = path.join(output, 'native-assets');
  const head = git(root, ['rev-parse', '--verify', 'HEAD^{commit}']).trim();
  const dirty = scopedDirty(root);
  const receipt = {
    schema: 'wrn.android-release-preparation.v1',
    generatedAt: now().toISOString(),
    sourceCommit: head,
    sourcePaths,
    dirty: { rejected: dirty.length > 0, entries: dirty },
    executesGradle: false,
    signing: false,
    upload: false,
  };
  if (dirty.length > 0) {
    await writeFile(path.join(output, 'receipt.json'), `${JSON.stringify(receipt, null, 2)}\n`, {
      flag: 'wx',
    });
    fail(`tracked Android source is dirty; rejected receipt: ${path.join(output, 'receipt.json')}`);
  }
  await mkdir(stage);
  const records = [];
  let total = 0;
  const dist = path.join(root, 'apps/mobile/dist');
  for (const file of await listFiles(root, dist, 'apps/mobile/dist')) {
    const bytes = (await regularFile(root, file.absolute, `apps/mobile/dist/${file.relative}`))
      .bytes;
    total += bytes.byteLength;
    if (total > maximumTotalBytes) fail('apps/mobile/dist exceeds the staging limit');
    await writeFresh(stage, `public/${file.relative}`, bytes, records);
  }
  const distRecords = records.length;
  const index = records.find((entry) => entry.path === 'public/index.html');
  if (distRecords === 0 || !index || index.bytes === 0)
    fail('apps/mobile/dist must contain a staged public/index.html');
  for (const bridgePath of bridgePaths) {
    const bytes = (await regularFile(root, path.join(root, bridgePath), bridgePath)).bytes;
    total += bytes.byteLength;
    if (total > maximumTotalBytes) fail('native bridge assets exceed the staging limit');
    const assetPrefix = 'apps/mobile/android/app/src/main/assets/';
    await writeFresh(stage, bridgePath.slice(assetPrefix.length), bytes, records);
  }
  const resolvedCapacitorBridgePath =
    capacitorBridgePath ??
    path.join(
      root,
      'apps/mobile/node_modules/@capacitor/android/capacitor/src/main/assets/native-bridge.js',
    );
  const capacitorBridge = await regularDependencyFile(
    root,
    resolvedCapacitorBridgePath,
    '@capacitor/android native bridge',
  );
  total += capacitorBridge.bytes.byteLength;
  if (total > maximumTotalBytes) fail('native bridge assets exceed the staging limit');
  await writeFresh(stage, 'native-bridge.js', capacitorBridge.bytes, records);
  const ordered = records.sort((left, right) => left.path.localeCompare(right.path));
  await writeFresh(
    output,
    'native-assets.json',
    Buffer.from(`${JSON.stringify(ordered, null, 2)}\n`),
    [],
  );
  const complete = {
    ...receipt,
    dirty: { rejected: false, entries: [] },
    distFiles: distRecords,
    distProvenance: {
      status: 'unverified',
      reason:
        'The staged dist hash list binds bytes but does not prove which source build produced them.',
    },
    assets: ordered,
    stagedBytes: total,
    nativeAssetsSha256: sha256(Buffer.from(JSON.stringify(ordered))),
    assetsDirectory: 'native-assets',
    initScript: 'unsigned-bundle.init.gradle',
    laterGradleCommand:
      '.\\gradlew.bat --offline --no-daemon -I <stage>/unsigned-bundle.init.gradle -Dwrn.receipt=<stage>/receipt.json -Dwrn.assets=<stage>/native-assets :app:bundleRelease',
  };
  const receiptPath = path.join(output, 'receipt.json');
  const receiptBytes = Buffer.from(`${JSON.stringify(complete, null, 2)}\n`);
  await writeFile(receiptPath, receiptBytes, { flag: 'wx' });
  await writeFresh(
    output,
    'unsigned-bundle.init.gradle',
    Buffer.from(initScript(receiptPath, sha256(receiptBytes))),
    [],
  );
  return { output, receipt: complete, assets: ordered };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  try {
    const result = await prepareAndroidRelease();
    console.log(
      JSON.stringify({
        output: result.output,
        sourceCommit: result.receipt.sourceCommit,
        assets: result.assets.length,
      }),
    );
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
