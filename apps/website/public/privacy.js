const language = new URLSearchParams(location.search).get('lang');
const selected = Object.hasOwn(copy, language) ? language : 'en';
const select = document.querySelector('#language');
for (const [id, value] of Object.entries(copy)) {
  const option = document.createElement('option');
  option.value = id;
  option.textContent = value.name;
  option.selected = id === selected;
  select.append(option);
}
function render(id) {
  const value = copy[id] ?? copy.en;
  document.documentElement.lang = id;
  document.title = `${value.title} · World Revolution News`;
  for (const node of document.querySelectorAll('[data-copy]'))
    node.textContent = value[node.dataset.copy];
}
select.addEventListener('change', () => {
  const url = new URL(location.href);
  url.searchParams.set('lang', select.value);
  history.replaceState(null, '', url);
  render(select.value);
});
render(selected);
